// JavaScript / TypeScript rules. Patterns run against comment-stripped code; `taintSink` rules fire
// only when user-controlled data (direct source or tainted variable) reaches the sink argument.
const L = ['javascript', 'typescript'];
const QS = String.raw`(?:"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')`; // a complete '…' or "…" literal
// "Evil regex" shape: a group whose body is one quantified atom (optionally followed by optional atoms),
// itself quantified — (a+)+, (\w*)*, (\w+\s?)*. Delimited repeats like (,\w+)* are linear and not matched.
const EVIL_ATOM = String.raw`(?:\[[^\]\n]+\]|\\.|[^()\\|\n])`;
const EVIL = String.raw`\((?:\?:)?` + EVIL_ATOM + String.raw`[+*](?:` + EVIL_ATOM + String.raw`[?*])*\)[+*{]`;
